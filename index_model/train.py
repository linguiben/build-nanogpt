"""简化指数模型：从三只模拟股票的价格中，学习计算当天指数的权重。

当前仅包含注释与伪代码，用于理解模型训练六部曲。
股票 A/B/C 的基准价格为 10/50/100 元，指数基准点位为 100。
输入为相对固定基准日的价格变化率，输出为当天指数相对基准点位的变化率。
"""

# 1. 建模：三个输入、一个输出、三个可学习权重，不使用偏置。
#   x = [rA, rB, rC]，其中 r = 当天价格 / 基准价格 - 1
#   模型 = Linear(输入维度=3, 输出维度=1, bias=False)
#   预测变化率 y_hat = wA*rA + wB*rB + wC*rC
#   预测指数 = 100 * (1 + y_hat)

# 2. 准备数据：模拟三只股票分别变化的价格，用已知规则生成标签。
#   真实权重 = [0.5, 0.3, 0.2]，仅用于生成标签和最终检查，不直接赋给模型
#   随机生成多组价格 → 转换为 x → 计算 y = 0.5*rA + 0.3*rB + 0.2*rC
#   将样本分为训练集和测试集；一个 batch 的 x 形状为 [B,3]，y 为 [B,1]
#   例：价格 [11,45,120] → x=[0.1,-0.1,0.2] → y=0.06 → 指数=106

# 3. 模型初始化，准备训练：从未知权重开始，用梯度下降寻找合适的参数。
#   固定随机种子，在 CPU 上初始化模型的随机权重
#   损失函数 = 均方误差 MSE；优化器 = SGD(模型参数, 学习率)
#   设置训练步数、batch size，记录初始权重和初始误差

# 4. 正向传播计算 loss：用当前权重预测，再衡量预测与标签的差距。
#   对每一个训练步：
#       x, y = get_batch(训练集)
#       optimizer.zero_grad()                 # 清除旧梯度，不清空权重
#       y_hat = model(x)                      # [B,3] → [B,1]
#       loss = mean((y_hat - y)**2)           # 一个标量，越小表示预测越准确

# 5. 反向传播更新权重：紧接第 4 步，在同一个训练循环中执行。
#       loss.backward()                      # 计算梯度，尚未修改权重
#       optimizer.step()                     # SGD 更新：w = w - 学习率 * 梯度
#       首步打印输入、预测、loss、梯度及更新前后的权重；后续定期打印进度
# 核心循环：get_batch → zero_grad → forward → loss → backward → step。

# 6. 验证与评估：使用未参与参数更新的测试集，检查预测和学到的规律。
#   model.eval()；关闭梯度记录；计算测试集的预测变化率
#   转回指数点位，比较预测指数与真实指数，报告平均绝对误差
#   检查学到的权重是否接近 [0.5,0.3,0.2]；输入 [0,0,0] 时指数应为 100
#   测试集不执行 backward 或 optimizer.step；训练结果须由实际误差验证
